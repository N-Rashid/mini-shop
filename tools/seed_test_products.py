def now_iso():
    return datetime.now(timezone.utc).strftime('%Y-%m-%dT%H:%M:%SZ')


def load_categories(conn):
    return conn.execute('''
        SELECT id, name, sort_order
        FROM categories
        WHERE deleted_at IS NULL AND COALESCE(is_featured_home, 0) = 0
        ORDER BY sort_order ASC, id ASC
    ''').fetchall()


def pick_category(categories, index):
    return categories[index % len(categories)]


def main():
    conn = sqlite3.connect(DB_PATH)
    conn.row_factory = sqlite3.Row

    categories = load_categories(conn)
    if not categories:
        print('Нет категорий для привязки товаров.')
        conn.close()
        return

    existing = {
        row['name'] for row in conn.execute(
            "SELECT name FROM products WHERE deleted_at IS NULL"
        ).fetchall()
    }

    next_sort = conn.execute(
        'SELECT COALESCE(MAX(sort_order), 0) FROM products WHERE deleted_at IS NULL'
    ).fetchone()[0]

    category_counters = {
        cat['id']: conn.execute(
            'SELECT COALESCE(MAX(sort_order), 0) FROM product_categories WHERE category_id = ?',
            (cat['id'],),
        ).fetchone()[0]
        for cat in categories
    }

    added = 0
    for index, (name, description, price_pack, pieces, weight, price_piece) in enumerate(PRODUCT_TEMPLATES):
        if name in existing:
            continue

        category = pick_category(categories, index)
        category_id = category['id']
        allow_piece = 1 if price_piece is not None else 0
        piece_price = float(price_piece) if price_piece is not None else 0.0
        next_sort += 1
        category_counters[category_id] += 1

        cur = conn.execute(
            '''
            INSERT INTO products (
                name, cost, pieces_per_box, weight, description, created_at,
                category_id, price_piece, price_pack, allow_piece_sale,
                is_on_sale, sale_price_pack, sale_price_piece, is_bestseller,
                sort_order, in_stock
            ) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, 0, NULL, NULL, 0, ?, 1)
            ''',
            (
                name,
                float(price_pack),
                int(pieces),
                float(weight),
                description,
                now_iso(),
                category_id,
                piece_price,
                float(price_pack),
                allow_piece,
                next_sort,
            ),
        )
        product_id = cur.lastrowid
        conn.execute(
            '''
            INSERT OR REPLACE INTO product_categories (product_id, category_id, sort_order)
            VALUES (?, ?, ?)
            ''',
            (product_id, category_id, category_counters[category_id]),
        )
        added += 1

    conn.commit()
    total = conn.execute(
        'SELECT COUNT(*) AS c FROM products WHERE deleted_at IS NULL'
    ).fetchone()['c']
    conn.close()
    print(f'Добавлено товаров: {added}')
    print(f'Пропущено (уже были): {len(PRODUCT_TEMPLATES) - added}')
    print(f'Всего активных товаров: {total}')


if __name__ == '__main__':
    main()
